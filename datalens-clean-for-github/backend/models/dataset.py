from sqlalchemy import Column, Integer, String, Float, DateTime, ForeignKey, JSON
from sqlalchemy.sql import func
from core.database import Base

class Dataset(Base):
    __tablename__ = "datasets"

    id = Column(Integer, primary_key=True, index=True)
    filename = Column(String, index=True)
    original_path = Column(String)
    status = Column(String, default="uploaded") # uploaded, processing, ready, failed
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    owner_id = Column(Integer, ForeignKey("users.id"))
    
    # Analysis metadata stored as JSON
    row_count = Column(Integer, nullable=True)
    column_count = Column(Integer, nullable=True)
    missing_values_percent = Column(Float, nullable=True)
    duplicate_count = Column(Integer, nullable=True)
    
    schema_info = Column(JSON, nullable=True) # Column types
    ai_insights = Column(JSON, nullable=True) # Text generated by AI
    stats = Column(JSON, nullable=True) # High level stats (revenue, etc.)
